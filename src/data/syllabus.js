// Helper to generate the exact IndiaBIX URL for any topic
export function getIndiaBixUrl(catId, subcatId, topicId, questionNum = null) {
  // Map our subcategory to the official URL structure
  let baseUrl = "https://www.indiabix.com";
  
  if (subcatId === "arithmetic") {
    return `${baseUrl}/aptitude/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "di") {
    return `${baseUrl}/data-interpretation/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "logical") {
    return `${baseUrl}/logical-reasoning/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "verbal-reasoning") {
    return `${baseUrl}/verbal-reasoning/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "non-verbal") {
    return `${baseUrl}/non-verbal-reasoning/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "verbal-ability") {
    return `${baseUrl}/verbal-ability/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  } else if (subcatId === "languages" || subcatId === "technical" || subcatId === "branches") {
    // These typically look like: https://www.indiabix.com/c-programming/questions-and-answers/
    // or with sections. We can link to the standard QA landing.
    return `${baseUrl}/${topicId}/questions-and-answers/`;
  } else if (subcatId === "gk-topics") {
    return `${baseUrl}/general-knowledge/${topicId}/${questionNum ? `discussion-${questionNum}` : ''}`;
  }
  
  return `${baseUrl}/`;
}
